import type { AuditResult } from './types.js';
import { humanResult } from './reporting.js';

export function renderAudit(result: AuditResult, legacy = false, legacyBrand = false): string {
  const brand = legacyBrand ? 'Usual Design' : 'Usual UI';
  return `<!-- Generated by ${brand}. Keep manual notes in a separate file. -->
# ${brand} audit

Snapshot: ${result.snapshot}

\`\`\`text
${legacy ? legacyHumanResult(result, brand) : humanResult(result).replace(/^Usual UI/, brand)}
\`\`\`

Inactive categories are unchecked by lint. Re-audit before resuming deferred work.
`;
}

/** Only exact known generated formats may be replaced; manual content is never discarded. */
export function isGeneratedAudit(markdown: string, previous: AuditResult): boolean {
  return [false, true].some((legacy) =>
    [false, true].some((legacyBrand) => markdown === renderAudit(previous, legacy, legacyBrand)),
  );
}

// Kept byte-for-byte compatible with audit Markdown generated before grouped reporting.
function legacyHumanResult(r: AuditResult, brand: string): string {
  const lines = [
    `${brand} ${r.mode}: ${r.files.length} files`,
    `Active: ${r.active.join(', ') || 'none — no design enforcement'}`,
    `Inactive: ${r.inactive.join(', ') || 'none'}`,
  ];
  if (r.coverage)
    lines.push(
      `Include: ${r.coverage.include.join(', ')}`,
      `Configured excludes: ${r.coverage.ignore.join(', ') || 'none'}; standard dependency/build exclusions also apply.`,
      `Exceptions used: ${r.coverage.exceptionsUsed.length}`,
    );
  if (r.coverage?.exceptionsUnused !== undefined)
    lines.push(
      `Exceptions unused in this run: ${r.coverage.exceptionsUnused.length}; review them in a full audit before removal.`,
    );
  for (const e of r.errors) lines.push(`ERROR ${e}`);
  for (const f of r.findings)
    lines.push(
      `${f.file}:${f.line}:${f.column} [${f.ruleId}] ${f.message}${f.expected ? ` Expected: ${f.expected}` : ''}`,
    );
  lines.push(`${r.findings.length} findings; ${r.errors.length} operational errors.`);
  return lines.join('\n');
}
